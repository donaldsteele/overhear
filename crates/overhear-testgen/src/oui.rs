//! Generates `crates/overhear/src/vendor/table.rs` from the IEEE registry CSV files.

use std::collections::BTreeSet;
use std::fmt::Write as _;

/// Split CSV text into records of fields. Handles quoted fields with commas,
/// doubled quotes and newlines inside quotes.
fn records(text: &str) -> Result<Vec<Vec<String>>, String> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut out = Vec::new();
    let mut row: Vec<String> = Vec::new();
    let mut field = String::new();
    let mut quoted = false;
    let mut after_quote = false;
    let mut chars = text.chars().peekable();
    while let Some(c) = chars.next() {
        if quoted {
            if c == '"' {
                if chars.peek() == Some(&'"') {
                    chars.next();
                    field.push('"');
                } else {
                    quoted = false;
                    after_quote = true;
                }
            } else {
                field.push(c);
            }
            continue;
        }
        match c {
            '"' if field.is_empty() && !after_quote => quoted = true,
            ',' => {
                row.push(std::mem::take(&mut field));
                after_quote = false;
            }
            '\r' => {}
            '\n' => {
                row.push(std::mem::take(&mut field));
                after_quote = false;
                if row.iter().any(|f| !f.is_empty()) {
                    out.push(std::mem::take(&mut row));
                } else {
                    row.clear();
                }
            }
            _ => field.push(c),
        }
    }
    if quoted {
        return Err("unterminated quoted field".into());
    }
    if !field.is_empty() || !row.is_empty() {
        row.push(field);
        out.push(row);
    }
    Ok(out)
}

/// Parse one IEEE CSV file into (assignment hex, organisation name) pairs.
pub fn parse_csv(text: &str) -> Result<Vec<(String, String)>, String> {
    let mut rows = records(text)?.into_iter();
    match rows.next() {
        Some(h) if h.len() >= 3 && h[1].trim() == "Assignment" => {}
        _ => return Err("missing CSV header (Registry,Assignment,Organization Name,...)".into()),
    }
    let mut out = Vec::new();
    for (n, r) in rows.enumerate() {
        if r.len() < 3 {
            return Err(format!("record {} has {} fields", n + 2, r.len()));
        }
        let name = r[2].split_whitespace().collect::<Vec<_>>().join(" ");
        out.push((r[1].trim().to_string(), name));
    }
    Ok(out)
}

/// Parse a CSV into sorted (key, name) pairs, keeping the first entry for a repeated key.
fn entries(csv: &str, hex_len: usize, what: &str) -> Result<Vec<(u64, String)>, String> {
    let mut v = Vec::new();
    for (hex, name) in parse_csv(csv).map_err(|e| format!("{what}: {e}"))? {
        if hex.len() != hex_len {
            return Err(format!(
                "{what}: assignment {hex:?} is not {hex_len} hex digits"
            ));
        }
        let key = u64::from_str_radix(&hex, 16)
            .map_err(|e| format!("{what}: assignment {hex:?}: {e}"))?;
        if name.is_empty() {
            return Err(format!("{what}: assignment {hex} has no organisation name"));
        }
        v.push((key, name));
    }
    v.sort_by_key(|e| e.0); // stable: first occurrence wins below
    v.dedup_by_key(|e| e.0);
    Ok(v)
}

fn table(
    out: &mut String,
    name: &str,
    ty: &str,
    rows: &[(u64, String)],
    names: &[String],
) -> Result<(), String> {
    write!(out, "pub static {name}: &[({ty}, u16)] = &[").map_err(|e| e.to_string())?;
    for (i, (k, n)) in rows.iter().enumerate() {
        let idx = names
            .binary_search(n)
            .map_err(|_| "name missing".to_string())?;
        if i > 0 {
            out.push_str(", ");
        }
        write!(out, "({k:#X}, {idx})").map_err(|e| e.to_string())?;
    }
    out.push_str("];\n");
    Ok(())
}

/// Rust source of `table.rs`.
pub fn gen_oui(mal_csv: &str, mam_csv: &str, mas_csv: &str) -> Result<String, String> {
    let mal = entries(mal_csv, 6, "MA-L")?;
    let mam = entries(mam_csv, 7, "MA-M")?;
    let mas = entries(mas_csv, 9, "MA-S")?;
    let names: Vec<String> = mal
        .iter()
        .chain(&mam)
        .chain(&mas)
        .map(|e| e.1.clone())
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();
    if names.len() > usize::from(u16::MAX) + 1 {
        return Err(format!(
            "{} distinct names do not fit a u16 index",
            names.len()
        ));
    }
    let mut out = String::new();
    out.push_str(
        "// Generated by `testgen gen-oui` (scripts/update-oui.sh). Do not edit.\n\
         // Source: IEEE Registration Authority\n\
         //   https://standards-oui.ieee.org/oui/oui.csv\n\
         //   https://standards-oui.ieee.org/oui28/mam.csv\n\
         //   https://standards-oui.ieee.org/oui36/oui36.csv\n\n\
         #![allow(clippy::unreadable_literal)]\n\n",
    );
    out.push_str("pub static NAMES: &[&str] = &[");
    for (i, n) in names.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        write!(out, "{n:?}").map_err(|e| e.to_string())?;
    }
    out.push_str("];\n");
    table(&mut out, "MA_L", "u32", &mal, &names)?;
    table(&mut out, "MA_M", "u32", &mam, &names)?;
    table(&mut out, "MA_S", "u64", &mas, &names)?;
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn csv_quotes_and_commas() {
        let t = "Registry,Assignment,Organization Name,Organization Address\nMA-L,001122,\"Big Co, Inc.\",\"x\"\nMA-M,0011223,\"Small \"\"Q\"\" Ltd\",y\n";
        assert_eq!(
            parse_csv(t).unwrap(),
            vec![
                ("001122".into(), "Big Co, Inc.".into()),
                ("0011223".into(), "Small \"Q\" Ltd".into())
            ]
        );
    }

    const HDR: &str = "Registry,Assignment,Organization Name,Organization Address\n";

    #[test]
    fn generates_sorted_deduplicated_tables() {
        let mal = format!(
            "{HDR}MA-L,00AABB,  Zed \u{e9} Corp ,a\nMA-L,0000cc,Alpha,b\nMA-L,00AABB,Zed \u{e9} Corp,dup\n"
        );
        let mam = format!("{HDR}MA-M,1234567,Alpha,c\n");
        let mas = format!("{HDR}MA-S,123456789,Beta,d\n");
        let a = gen_oui(&mal, &mam, &mas).unwrap();
        assert_eq!(a, gen_oui(&mal, &mam, &mas).unwrap());
        assert!(
            a.contains("pub static NAMES: &[&str] = &[\"Alpha\", \"Beta\", \"Zed \u{e9} Corp\"];"),
            "{a}"
        );
        assert!(
            a.contains("pub static MA_L: &[(u32, u16)] = &[(0xCC, 0), (0xAABB, 2)];"),
            "{a}"
        );
        assert!(
            a.contains("pub static MA_M: &[(u32, u16)] = &[(0x1234567, 0)];"),
            "{a}"
        );
        assert!(
            a.contains("pub static MA_S: &[(u64, u16)] = &[(0x123456789, 1)];"),
            "{a}"
        );
    }

    #[test]
    fn rejects_bad_assignment() {
        let bad = format!("{HDR}MA-L,00AB,X,y\n");
        let ok = HDR.to_string();
        assert!(gen_oui(&bad, &ok, &ok).is_err());
    }
}
